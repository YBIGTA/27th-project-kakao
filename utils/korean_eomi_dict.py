# --------- 보너스: 끝말부호/심볼 스트립(매칭 전) ----------
TRAIL_PUNCT_SYM_RE = re.compile(r"[\p{P}\p{S}\s]+$")  # 문장 끝의 구두점/기호/공백 제거

def strip_trailing_punct(s: str) -> str:
    """문장 끝의 문장부호/기호/공백 제거 후 반환"""
    return TRAIL_PUNCT_SYM_RE.sub("", s or "")

# --------- 문맥 점수 계산 함수 ----------
def get_eomi_context_score(text: str, eomi: str, eomi_start: int = -1) -> float:
    """
    종결어미의 문맥 점수를 계산
    - 앞에 한글이 오면 가점 (+1.0)
    - 앞에 스페이스가 오면 -3점
    - 뒤에 한글이 오면 -4점
    - 뒤에 문장부호가 오면 +3점
    - 뒤에 공백이 오면 +2점
    """
    score = 1.0

    # 종결어미 위치 찾기
    if eomi_start >= 0:
        eomi_pos = eomi_start
    else:
        eomi_pos = text.rfind(eomi)
    
    if eomi_pos < 0:
        return 0.0

    # 앞에 한글이 오는 경우 가점
    if eomi_pos > 0:
        prev_char = text[eomi_pos - 1]
        if '\uAC00' <= prev_char <= '\uD7AF':  # 한글 범위
            score += 1.0  # 가점 (+1.0)
        elif prev_char.isspace():  # 스페이스인 경우
            score -= 3.0  # -3점

    # 뒤에 문자가 오는 경우
    if eomi_pos + len(eomi) < len(text):
        next_char = text[eomi_pos + len(eomi)]
        if '\uAC00' <= next_char <= '\uD7AF':  # 한글이 오는 경우
            score -= 4.0  # -4점
        elif next_char in '.!?…':  # 문장부호가 오는 경우
            score += 3.0  # +3점
        elif next_char.isspace():  # 공백이 오는 경우
            score += 2.0  # +2점

    return score
